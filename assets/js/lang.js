const langEnBtn = document.querySelector('.lang-en');
const langEsBtn = document.querySelector('.lang-es');

// Initial setup
let currentLang = localStorage.getItem('selectedLang') || 'en';
setLanguage(currentLang);

// Listeners
if(langEnBtn && langEsBtn) {
    langEnBtn.addEventListener('click', () => {
        setLanguage('en');
    });
    
    langEsBtn.addEventListener('click', () => {
        setLanguage('es');
    });
}

function setLanguage(lang) {
    currentLang = lang;
    localStorage.setItem('selectedLang', lang);

    // Update UI Toggle Buttons
    if (lang === 'en') {
        langEnBtn.style.color = 'var(--primary-color)';
        langEsBtn.style.color = 'var(--text-color)';
    } else {
        langEnBtn.style.color = 'var(--text-color)';
        langEsBtn.style.color = 'var(--primary-color)';
    }

    // Replace Text
    const elements = document.querySelectorAll('[data-i18n]');
    elements.forEach((el) => {
        const key = el.getAttribute('data-i18n');
        if (translations[lang][key]) {
            el.innerHTML = translations[lang][key];
        }
    });
}
